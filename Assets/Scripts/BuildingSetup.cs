    private void Start()
    {
        SetupBuildings();
    }

    private void SetupBuildings()
    {
        Transform buildingsParent = transform;

        for (int i = 0; i < buildingsParent.childCount; i++)
        {
            Transform child = buildingsParent.GetChild(i);
            BuildingInfo info = child.GetComponent<BuildingInfo>();

            if (info == null)
                info = child.gameObject.AddComponent<BuildingInfo>();

            if (i < BuildingNames.Length)
            {
                if (string.IsNullOrEmpty(info.buildingName) || info.buildingName == "Корпус ПГНИУ")
                    info.buildingName = BuildingNames[i];

                if (string.IsNullOrEmpty(info.description) || info.description == "Описание корпуса")
                    info.description = BuildingDescriptions[i];
            }
        }

        Debug.Log($"[BuildingSetup] Настроено {buildingsParent.childCount} корпусов");
    }
}
